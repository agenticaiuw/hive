const {readFileSync} = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = readFileSync('dashboard/index.html','utf8');
const code = html.slice(html.indexOf('function toolEntry('),html.indexOf('const badge'));
const {toolEntry,appendLogEntry} = vm.runInNewContext(code+';({toolEntry,appendLogEntry})', {document:{createElement:()=>({set innerHTML(v){this.content={firstElementChild:{className:'activity',getAttribute:()=> 'false',childNodes:[v]}}}})},esc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;')});
const command = {id:'c1',type:'commandExecution',status:'completed',command:'cat x',commandActions:[{type:'read',name:'x'}],aggregatedOutput:'<script>\n2\n3\n4\n5\n6',exitCode:0};
assert.match(toolEntry(command),/Explored/);
assert.match(toolEntry(command),/Read x/);
assert.match(toolEntry(command),/\+1 lines/);
assert.doesNotMatch(toolEntry(command),/<script>/);
assert.match(toolEntry({...command,commandActions:[],status:'inProgress'}),/Running cat x/);
assert.match(toolEntry({...command,exitCode:1}),/exit 1/);
assert.match(toolEntry({type:'mcpToolCall',tool:'mac_shell',arguments:{command:'ls'},output:'ok'}),/Called/);
assert.match(toolEntry({type:'fileChange',changes:[{path:'x',diff:'+hello'}]}),/\+hello/);
let replaced = '', appended = 0;
const old = {dataset:{toolId:'c1'},querySelector:()=>null,setAttribute:()=>{},replaceChildren:(v)=>{replaced=v}};
const box = {querySelectorAll:()=>[old],insertAdjacentHTML:()=>appended++};
appendLogEntry(box,{who:'tool-item',text:JSON.stringify(command)});
assert.match(replaced,/Explored/); assert.equal(appended,0);
appendLogEntry(box,{who:'agent',text:'done'}); assert.equal(appended,1);
console.log('Tool rendering, escaping, full output, failures, and poll reconciliation passed');
